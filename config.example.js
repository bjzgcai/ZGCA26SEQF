/**
 * 千帆竞发图 - 配置文件示例
 * 
 * ========================================
 * 文件结构：
 * ========================================
 * qfjf/
 * ├── index.html      # 模板（无需修改）
 * ├── config.js       # 配置文件
 * ├── data.csv        # 学生成绩（Tab分隔）
 * └── invest.csv      # 投资数据（Tab分隔）
 * 
 * ========================================
 * 使用方法：
 * ========================================
 * 1. 从 Excel 复制学生成绩，粘贴到 data.csv
 * 2. 从 Excel 复制投资数据，粘贴到 invest.csv
 * 3. 修改 config.js 中的列配置
 * 4. 启动服务器：python -m http.server
 * 5. 访问：http://localhost:8000
 * 
 * ========================================
 * data.csv 格式说明：
 * ========================================
 * - Tab 分隔
 * - 第一行是表头
 * - 每列都会被识别为成绩列，除非在 excludeColumns 中排除
 * 
 * 示例：
 * 年级	学号	姓名	签到1	签到2	作业1	...	总分
 * 2025	001	张三	1	1	5	...	100
 * 
 * ========================================
 * invest.csv 格式说明：
 * ========================================
 * - Tab 分隔
 * - 第一列是项目名称
 * - 后续每列是一个投资轮次，列名就是标题
 * 
 * 示例：
 * 项目名称	第一轮投资	Alpha投资	评委评价
 * 项目A	200	180	4.5
 * 项目B	150	200	3.8
 */

